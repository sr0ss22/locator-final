-- 0183: Bulk-link locator installers to Brite by contact email.
--
-- After 0181 (vendor-id backfill) + 0182 (manual mappings) we still had
-- ~159 unlinked. Investigation showed >90% of those locator rows have an
-- email that matches exactly one Brite install_company - their
-- installer_vendor_id is just a stale 5-digit legacy value while Brite
-- stores the new 8-digit vendor_number. Email is the reliable join.
--
-- This migration stages every Brite (email -> brite_company_id) pair where
-- the email is unique in Brite, then applies the link to any locator row
-- whose lower-trimmed email matches AND that doesn't already have a
-- brite_company_id. Locator rows already linked are NOT touched, so 0181
-- and 0182 results are preserved.
--
-- Ambiguous Brite emails (3) are deliberately skipped here for human review.
-- =============================================================================


-- Apply the link, only to currently-NULL rows so we don't disturb existing links.
WITH updated AS (
  UPDATE public.installers i
     SET brite_company_id = s.brite_company_id,
         brite_synced_at  = now()
    FROM _brite_email_link_staging s
   WHERE lower(trim(i.email)) = s.brite_email
     AND i.brite_company_id IS NULL
  RETURNING i.id, i.name, s.brite_company_id
)
SELECT count(*) AS rows_linked_by_email_backfill FROM updated;

-- Reconciliation summary.
SELECT
  (SELECT count(*) FROM public.installers)                              AS total_locator,
  (SELECT count(*) FROM public.installers WHERE brite_company_id IS NOT NULL) AS linked_to_brite,
  (SELECT count(*) FROM public.installers WHERE brite_company_id IS NULL)     AS still_unlinked,
  round(100.0 * (SELECT count(*) FROM public.installers WHERE brite_company_id IS NOT NULL)
              / (SELECT count(*) FROM public.installers), 1) AS pct_linked;

-- Show whoever is still unlinked after this pass (truncated to 200 rows).
SELECT name, email, primary_phone, installer_vendor_id, is_active
  FROM public.installers
 WHERE brite_company_id IS NULL
 ORDER BY is_active DESC NULLS LAST, name
 LIMIT 200;

